export function PixelIcon({ name, className = "" }: { name: string; className?: string }) {
  const rows = SPRITES[name] ?? SPRITES.other;
  const rects: React.ReactNode[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < 8; x++) {
      if (row[x] === "#") rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />);
    }
  });
  return (
    <svg className={`spr ${className}`} viewBox="0 0 8 8" aria-hidden="true" shapeRendering="crispEdges" fill="currentColor">
      {rects}
    </svg>
  );
}
